"""Rebuild contracts and regenerate sdk/src/abi.ts + sdk/src/bytecode.ts. Run: python3 scripts/abi.py"""
import json, os, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
env = {**os.environ, "PATH": f"{Path.home()}/.foundry/bin:{os.environ['PATH']}"}
subprocess.run(["forge", "build"], cwd=ROOT / "contracts", env=env, check=True, capture_output=True)
art = json.loads((ROOT / "contracts/out/VaubanVault.sol/VaubanVault.json").read_text())
head = "// generated by scripts/abi.py — do not edit\n"
(ROOT / "sdk/src/abi.ts").write_text(head + "export const vaubanVaultAbi = " + json.dumps(art["abi"], indent=1) + " as const;\n")
(ROOT / "sdk/src/bytecode.ts").write_text(head + f'export const vaubanVaultBytecode = "{art["bytecode"]["object"]}" as const;\n')
print("abi items", len(art["abi"]), "bytecode bytes", len(art["bytecode"]["object"]) // 2 - 1)
